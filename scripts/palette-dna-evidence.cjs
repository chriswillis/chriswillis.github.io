#!/usr/bin/env node
// Seeded hold-out for the Palette DNA engine. Plain Node (18+), no dependencies.
//
//   node scripts/palette-dna-evidence.cjs           run the test, write palette-dna/evidence.html
//   node scripts/palette-dna-evidence.cjs --check   run the test, fail if a published number or
//                                                   the committed evidence page differs from it
//
// Method (see docs/designs/palette-dna-tools.md, "Terms and measurement"):
// for each palette and each ramp the engine lofts, hide the ramp, seed with its most colorful
// step, rebuild it from that seed and the remaining ramps, and score every other step against
// the shipped ramp in Oklab distance x 100 (about 2 = one just-noticeable difference).
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'palette-dna/evidence.html');
const TEMPLATE = path.join(__dirname, 'palette-dna-evidence-template.html');
// Pages whose data-evidence numbers --check compares.
const PAGES = ['palette-dna/ramp.html', 'palette-dna/map.html'];
const SKIP = ['meridian-dark']; // a dark scale: steps run dark to light
const RUNS = ['auto', 'pinned', 'nearest'];

function load() {
  const c = vm.createContext({});
  for (const f of ['palettes', 'engine']) {
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/palette-dna', f + '.js'), 'utf8'), c);
  }
  return c;
}

const r2 = x => Math.round(x * 100) / 100;
const dE = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1], p[2] - q[2]) * 100;
const chroma = p => Math.hypot(p[1], p[2]);
const lch = p => [p[0], chroma(p), Math.atan2(p[2], p[1])];
const wrap = x => ((x + Math.PI) % (2 * Math.PI) + 2 * Math.PI) % (2 * Math.PI) - Math.PI;
const quant = (a, p) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.min(s.length - 1, Math.floor(p * s.length))] : null; };
// the headline set leaves out palettes generated by a formula and chart-color sets (palettes.js origin.kind)
const headline = pal => !(pal.origin && ['generated', 'chart'].includes(pal.origin.kind));

function run() {
  const { PALETTES, Engine: E } = load();
  const ramps = [];
  for (const pal of PALETTES) {
    if (SKIP.includes(pal.id)) continue;
    const M = E.build(pal, pal.neutral, pal.gamut);
    for (const r of M.loft) {
      const truth = r.labs;
      let k = r.keep[0];
      for (const kk of r.keep) if (chroma(truth[kk]) > chroma(truth[k])) k = kk;
      const seed = truth[k];
      const M2 = E.holdOut(M, r.name);
      const map = M2.seedMap(seed);
      const out = {};
      const auto = M2.genAnchors([{ lab: seed, map }], { cap: false });
      out.auto = auto.map(x => [x.L, x.a, x.b]);
      // the same seed, pinned to the step its designers used
      out.pinned = M2.genAnchors([{ lab: seed, map, step: pal.steps[k] }], { cap: false }).map(x => [x.L, x.a, x.b]);
      // baseline: the nearest remaining ramp, rotated to the seed's hue, chroma scaled at the seed step
      const u = map.u !== undefined ? map.u : Math.atan2(seed[2], seed[1]);
      const nl = M2.loft[M2.nearestLoft(u)].labs.map(lch), sl = lch(seed);
      const ratio = nl[k][1] > 1e-4 ? sl[1] / nl[k][1] : 1;
      out.nearest = nl.map((p, i) => {
        if (i === k) return seed;
        const L = p[0], h = sl[2] + wrap(p[2] - nl[k][2]);
        const C = Math.min(p[1] * ratio, E.maxC(L, h, pal.gamut));
        return [L, C * Math.cos(h), C * Math.sin(h)];
      });
      const row = { pal: pal.id, palName: pal.name, ramp: r.name, steps: pal.steps, seed: pal.steps[k],
        headline: headline(pal), truth: truth.map(p => E.oklchStr(p[0], p[1], p[2])) };
      for (const run of RUNS) {
        const g = out[run];
        const err = truth.map((t, i) => (i === k ? null : r2(dE(g[i], t))));
        let j = 0; g.forEach((p, i) => { if (dE(p, seed) < dE(g[j], seed)) j = i; });
        const e = err.filter(x => x !== null);
        row[run] = { colors: g.map(p => E.oklchStr(p[0], p[1], p[2])), err, placed: pal.steps[j],
          mean: r2(e.reduce((a, b) => a + b, 0) / e.length) };
      }
      ramps.push(row);
    }
  }
  const stats = (rows, run) => {
    const all = [], un = [], sh = [];
    let moved = 0;
    for (const row of rows) {
      const e = row[run].err.filter(x => x !== null);
      all.push(...e);
      if (row[run].placed === row.seed) un.push(...e); else { sh.push(...e); moved++; }
    }
    return { median: quant(all, 0.5), p90: quant(all, 0.9), within1: all.filter(x => x < 2).length / all.length,
      seedMoved: moved / rows.length, medianUnshifted: quant(un, 0.5), medianShifted: quant(sh, 0.5) };
  };
  const H = ramps.filter(r => r.headline);
  const result = { generated: new Date().toISOString().slice(0, 10),
    n: { ramps: H.length, palettes: new Set(H.map(r => r.pal)).size }, headline: {}, palette: {}, ramps };
  for (const run of RUNS) result.headline[run] = stats(H, run);
  for (const id of new Set(ramps.map(r => r.pal))) {
    const rows = ramps.filter(r => r.pal === id);
    result.palette[id] = { name: rows[0].palName, headline: rows[0].headline };
    for (const run of RUNS) { const s = stats(rows, run); result.palette[id][run] = { median: s.median, within1: s.within1 }; }
  }
  return result;
}

function render(result, previous) {
  // keep the committed date when nothing else changed, so --check compares content, not the run date
  const data = previous && JSON.stringify({ ...result, generated: previous.generated }) === JSON.stringify(previous)
    ? previous : result;
  const json = JSON.stringify(data).replace(/</g, '\\u003c');
  return fs.readFileSync(TEMPLATE, 'utf8').replace('{{DATA}}', () => json);
}

function committedData() {
  if (!fs.existsSync(OUT)) return null;
  const m = fs.readFileSync(OUT, 'utf8').match(/<script id="evidence-data" type="application\/json">([\s\S]*?)<\/script>/);
  return m ? JSON.parse(m[1].replace(/\\u003c/g, '<')) : null;
}

function lookup(obj, key) { return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj); }

function check(result) {
  const problems = [];
  for (const page of PAGES) {
    const html = fs.readFileSync(path.join(ROOT, page), 'utf8');
    for (const m of html.matchAll(/data-evidence="([^"]+)"[^>]*>([^<]*)</g)) {
      const [, key, text] = m, value = lookup(result, key), shown = text.trim();
      if (typeof value !== 'number') { problems.push(`${page}: ${key} is not a number in the results`); continue; }
      let expect;
      if (shown.endsWith('%')) expect = Math.round(value * 100) + '%';
      else { const d = (shown.split('.')[1] || '').length; expect = value.toFixed(d); }
      if (shown !== expect) problems.push(`${page}: ${key} shows ${shown}, fresh run gives ${expect}`);
    }
  }
  const h = result.headline;
  if (h.pinned.median > h.auto.median) problems.push(`pinned median ${h.pinned.median} is worse than automatic ${h.auto.median}`);
  const previous = committedData();
  if (!previous) problems.push('palette-dna/evidence.html is missing; run without --check to create it');
  else if (render(result, previous) !== fs.readFileSync(OUT, 'utf8')) problems.push('palette-dna/evidence.html is out of date; rerun without --check');
  return problems;
}

function summary(result) {
  const f = s => `median ${s.median.toFixed(2)}  p90 ${s.p90.toFixed(2)}  within 1 JND ${Math.round(s.within1 * 100)}%  seed moved ${Math.round(s.seedMoved * 100)}%  unshifted/shifted ${s.medianUnshifted.toFixed(2)}/${s.medianShifted === null ? '-' : s.medianShifted.toFixed(2)}`;
  const lines = [`headline set: ${result.n.ramps} ramps in ${result.n.palettes} palettes`];
  for (const run of RUNS) lines.push(`  ${run.padEnd(8)} ${f(result.headline[run])}`);
  lines.push('auto median by palette: ' + Object.entries(result.palette).map(([id, p]) => `${id} ${p.auto.median.toFixed(2)}`).join(', '));
  return lines.join('\n');
}

if (require.main === module) {
  const result = run();
  console.log(summary(result));
  if (process.argv.includes('--check')) {
    const problems = check(result);
    if (problems.length) { console.error('\nEvidence check failed:\n  ' + problems.join('\n  ')); process.exit(1); }
    console.log('\nEvidence check passed.');
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, render(result, committedData()));
    console.log('\nwrote', path.relative(process.cwd(), OUT));
  }
}

module.exports = { run, check, PAGES };
